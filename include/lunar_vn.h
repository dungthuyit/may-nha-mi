inline int32_t julianDay(int d, int m, int y) {
  int a=(14-m)/12; y+=4800-a; m+=12*a-3;
  return d+(153*m+2)/5+365*y+y/4-y/100+y/400-32045;
}
inline LunarDate vietnameseLunar(int day, int month, int year) {
  if(year<2020 || year>2040) return {0,0,0,false,false};
  int32_t jd=julianDay(day,month,year);
  for(int i=int(sizeof(lunarMonths)/sizeof(lunarMonths[0]))-1;i>=0;--i)
    if(jd>=lunarMonths[i].jd) return {int(jd-lunarMonths[i].jd+1),lunarMonths[i].month,lunarMonths[i].year,bool(lunarMonths[i].leap),true};
  return {0,0,0,false,false};
}
